import io

p = 'docs/tz/MAINTENANCE.md'
s = io.open(p, encoding='utf-8').read()

# 1. Закрываем находку от 14.09 — проставляем ссылку на PR в колонку «Закрыто».
OLD = ('`applyBitrixBatchAction` обновляет только карточку пакета, а состояние пакета видно и в '
       'списке: после «Применить» список показывает прежнее состояние до ручного обновления. Там '
       'же: список пакетов усечён на 50 без подписи «показаны N из M». Оба — этап 2, лимит '
       'хотфиксов прогона исчерпан | ❌ дефект | — |')
NEW = ('`applyBitrixBatchAction` обновляет только карточку пакета, а состояние пакета видно и в '
       'списке: после «Применить» список показывает прежнее состояние до ручного обновления. Там '
       'же: список пакетов усечён на 50 без подписи «показаны N из M». Оба — этап 2, лимит '
       'хотфиксов прогона исчерпан | ❌ дефект | ✅ прогон №31: освежаются оба адреса (как давно '
       'делает откат) и список честно пишет «показаны последние N из M»; обе половины проверены '
       'мутацией |')
assert s.count(OLD) == 1, s.count(OLD)
s = s.replace(OLD, NEW, 1)

# 2. Новые записи прогона №31.
HEADER = '| Дата | Проверка | Находка | Вердикт | Закрыто |\n|---|---|---|---|---|\n'
assert s.count(HEADER) == 1
ROWS = (
    '| 20.09.2026 | С-6 | **Разобрана до причины половина «список не обновляется после Применить».** '
    'Страница списка пакетов объявлена `force-dynamic`, то есть из серверного кэша не отдаётся — '
    'казалось бы, `revalidatePath` ей не нужен. Но он сбрасывает ещё и **клиентский кэш маршрутов**, '
    'где лежит RSC-ответ страницы: без него список, открытый переходом после «Применить», показывал '
    'прежнее состояние. Откат это делал давно, применение — нет. Полезно на будущее: '
    '`force-dynamic` **не** означает «revalidatePath не нужен» | ℹ шум | — |\n'
    '| 20.09.2026 | С-6 | **Оговорка к той же находке.** Состояние пакета меняет **воркер**, уже '
    'после возврата действия, поэтому список сразу после «Применить» покажет `applying`, а не '
    '`applied` — и это правильно. Освежение списка чинит не задержку воркера, а то, что список '
    'застревал на состоянии ДО применения | ℹ шум | — |\n'
)
s = s.replace(HEADER, HEADER + ROWS, 1)
io.open(p, 'w', encoding='utf-8').write(s)
print('журнал: закрыта находка 14.09, добавлены 2 записи')
