import { describe, it, expect } from 'vitest';
import { join } from 'node:path';
import { readSource } from './helpers/source';

/**
 * СТРАЖ `Р-Э7-6` (этап 7): счётчик на «Главной» менеджера называется тем, что
 * он считает.
 *
 * Расхождение, найденное сверкой §16: подпись обещала «Пропущенные звонки», а
 * расчёт (`intakeCallWhere`) смотрит на очередь разбора — входящий, без
 * организации, без контакта, не закрыт, без лида — и поля `answeredAt` не
 * касается вовсе. Звонок, на который ответили и просто не разобрали, попадал в
 * «пропущенные»; настоящий пропуск с привязанной организацией — не попадал.
 *
 * Чинится НАЗВАНИЕ, а не расчёт: счётчик полезен как есть. Поэтому страж
 * двусторонний — он ловит и возврат старой подписи, и подмену расчёта на
 * «по `answeredAt`», после которой название снова разойдётся со смыслом.
 *
 * Мутация (проверено): вернуть «Пропущенные звонки» в подпись → «подпись не
 * обещает пропущенные» краснеет; заменить `intakeCallWhere` на фильтр по
 * `answeredAt` → «расчёт остался про очередь разбора» краснеет.
 */
const SRC = join(process.cwd(), 'src');
const SERVICE = readSource(join(SRC, 'lib/services/manager/myDay.ts'));
const CARD = readSource(join(SRC, 'components/manager/my-day-cards.tsx'));

describe('страж: «Входящие без разбора» названы честно (Р-Э7-6)', () => {
  it('подпись на экране не обещает «пропущенные звонки»', () => {
    expect(CARD).toContain('Входящие без разбора за сутки');
    // Проверяется вся разметка карточек, а не одна строка: вернуть старое
    // слово можно в любом месте файла.
    expect(CARD, 'подпись снова обещает то, чего счётчик не считает').not.toContain(
      'Пропущенные звонки'
    );
  });

  it('поле называется по смыслу, старого имени в коде нет', () => {
    expect(SERVICE).toContain('callsUnsorted');
    expect(CARD).toContain('data.callsUnsorted');
    expect(SERVICE, 'старое имя поля вернулось').not.toContain('callsMissed:');
  });

  it('расчёт остался про очередь разбора, а не про ответ на звонок', () => {
    // Если счётчик переведут на `answeredAt`, он станет другим показателем —
    // и название снова разойдётся со смыслом, только в другую сторону.
    expect(SERVICE, 'счётчик больше не про очередь разбора').toContain('intakeCallWhere(session)');
  });

  // Проверки «в коде есть объяснение, почему имя менялось» здесь НЕТ намеренно.
  // Она требует читать файл сырым текстом, а `guards.source-read-strips-comments`
  // это запрещает: страж, читающий исходник как есть, считает живым и
  // закомментированный код. Правило проекта сильнее удобной мелочи — причина
  // переименования записана в самом файле, в close-out этапа и в реестре сверки.
});
