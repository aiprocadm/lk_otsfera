import { readFileSync } from 'node:fs';
import { stripComments } from '@/lib/acceptance/screenRules';

/**
 * Чтение исходника продукта для стража, который проверяет НАЛИЧИЕ строки.
 *
 * Зачем отдельный помощник. Страж вида «в этом файле есть вызов `X()`»,
 * читающий файл как есть, считает вызовом и закомментированный вызов, и
 * упоминание в пояснении сверху файла. Проверено мутацией (`С-5`, прогон
 * №26): у `config.settings-from-ui` обе точки — прайм снапшота флагов в
 * `instrumentation.ts` и в воркере — прошли зелёными после того, как строку
 * `await primeFeatureFlagCache(prisma);` просто закомментировали. Удаление
 * страж ловит, комментирование — нет; а для продукта это одно и то же:
 * снапшот не праймится, флаг из интерфейса не действует до первого входа.
 *
 * Годится ТОЛЬКО для `.ts`/`.tsx`. Разметке (`.md`), `.env`-примерам и
 * `schema.prisma` этот помощник не подходит: снятие `//` съест ссылки вида
 * `https://...` вместе с остатком строки.
 */
export function readSource(path: string): string {
  return stripComments(readFileSync(path, 'utf8'));
}
