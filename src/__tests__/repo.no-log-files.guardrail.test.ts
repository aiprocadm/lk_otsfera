import { describe, it, expect } from 'vitest';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';

/**
 * `У-259` (дефект `Д-41`) — под контролем версий не должно быть лог-файлов.
 *
 * Как это случилось. В `.gitignore` логи перечислялись поимённо
 * (`dev-server.log`, `worker.dev.log`, …), и список отставал от жизни: стоило
 * запустить сид или воркер с перенаправлением вывода в файл с другим именем —
 * и `seed.out.log`, `worker.log` спокойно уезжали в коммит. Так их и приехало
 * четыре. Ни один тест этого не замечал: лог-файл ничего не ломает, он просто
 * лежит в корне и растёт.
 *
 * Правило обобщено до `*.log`, а этот страж держит его честным: он смотрит не
 * в `.gitignore` (там правило можно случайно ослабить), а в сам индекс git —
 * единственный источник правды о том, что реально под версиями.
 *
 * Исключений нет намеренно. Лог — это вывод прогона, он воспроизводится
 * запуском; хранить его рядом с кодом незачем. Если однажды понадобится
 * приложить лог к расследованию, его место — вложение в задачу или PR, а не
 * рабочее дерево.
 */
const REPO_ROOT = join(__dirname, '..', '..');

/** Список путей под git. Работает и в worktree: `.git` там файл-указатель. */
function trackedFiles(): string[] {
  const out = execFileSync('git', ['ls-files', '-z'], {
    cwd: REPO_ROOT,
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
  });
  return out.split('\0').filter((p) => p.length > 0);
}

describe('репозиторий: логи не хранятся под git (У-259)', () => {
  it('ни один файл под контролем версий не оканчивается на .log', () => {
    const logs = trackedFiles().filter((p) => p.toLowerCase().endsWith('.log'));
    expect(
      logs,
      `Под git попали лог-файлы: ${logs.join(', ')}.\n` +
        'Уберите их из индекса (`git rm --cached <файл>`) — правило `*.log` в .gitignore\n' +
        'не действует на то, что уже отслеживается.'
    ).toEqual([]);
  });

  it('.gitignore закрывает класс целиком, а не имена поимённо', () => {
    // Проверка ОТСУТСТВИЯ поимённого списка не нужна — старые строки могут
    // остаться как документация. Нужна только строка общего правила: без неё
    // следующий лог с новым именем снова приедет в коммит.
    // `git check-ignore` выходит с кодом 1, когда путь НЕ игнорируется, а
    // execFileSync превращает ненулевой код в исключение. Ловим его и говорим
    // человеческим текстом: иначе страж падал бы словами «Command failed».
    let rules = '';
    try {
      rules = execFileSync('git', ['check-ignore', '-v', 'какой-угодно-новый.log'], {
        cwd: REPO_ROOT,
        encoding: 'utf8',
      });
    } catch {
      rules = '';
    }
    expect(
      rules,
      'В .gitignore нет общего правила `*.log`: новый лог с непредусмотренным именем\n' +
        'снова уедет в коммит. Верните строку `*.log`.'
    ).toContain('*.log');
  });
});
