import { describe, expect, it } from 'vitest';

import {
  counterpartyKey,
  organizationNameKey,
} from '@/lib/services/import/oneCAccountCard/counterparty-key';

// `У-83`: ключ контрагента — нормализованное наименование. Один и тот же ключ
// для «ООО Ромашка», «РОМАШКА, ООО» и «ромашка ооо»; орг-форма вынесена в
// отдельное поле; `ё → е`; кавычки/пунктуация игнорируются. Таблица пар —
// контракт нормализации: SQL-бэкфилл миграции сверяется с этой же функцией
// тестом паритета (import.card51.counterparty-key.sql-parity).
describe('counterpartyKey (У-83)', () => {
  const cases: Array<[raw: string, key: string, orgForm: string | null]> = [
    ['ООО «Ромашка»', 'РОМАШКА', 'ООО'],
    ['РОМАШКА, ООО', 'РОМАШКА', 'ООО'],
    ['ромашка ооо', 'РОМАШКА', 'ООО'],
    // Дефект прежней normalizeName: форма без пунктуации вокруг не срезалась
    // (`\b` в JS не работает на границе кириллицы).
    ['ХОЛДИНГ ГЕФЕСТ ООО', 'ХОЛДИНГ ГЕФЕСТ', 'ООО'],
    ['Ёлки-Палки АО', 'ЕЛКИ ПАЛКИ', 'АО'],
    ['ИП Иванов И.И.', 'ИВАНОВ И И', 'ИП'],
    ['  ПАО  Газпром  ', 'ГАЗПРОМ', 'ПАО'],
    ['ЗАО "Вектор"', 'ВЕКТОР', 'ЗАО'],
    ['ФГУП НИИ Связи', 'НИИ СВЯЗИ', 'ФГУП'],
    ['МУП Водоканал', 'ВОДОКАНАЛ', 'МУП'],
    ['ГБУ Жилищник', 'ЖИЛИЩНИК', 'ГБУ'],
    ['МБУ Спортшкола', 'СПОРТШКОЛА', 'МБУ'],
    ['ОАО Заря', 'ЗАРЯ', 'ОАО'],
    ['НКО Фонд Мира', 'ФОНД МИРА', 'НКО'],
    ['АНО ДПО Учебный центр', 'ДПО УЧЕБНЫЙ ЦЕНТР', 'АНО'],
    // Две формы подряд: обе уходят из ключа, в orgForm — первая.
    ['ООО АО Ромашка', 'РОМАШКА', 'ООО'],
    ['Фонд АНО НКО', 'ФОНД', 'АНО'],
    // Форма внутри слова — не форма.
    ['Сипайлово', 'СИПАЙЛОВО', null],
    ['ПРООО-Сервис', 'ПРООО СЕРВИС', null],
    // Имя из одной формы: ключа не остаётся.
    ['ООО', '', 'ООО'],
    ['', '', null],
    ['Servicetrade Ltd.', 'SERVICETRADE LTD', null],
  ];

  it.each(cases)('«%s» → key «%s», форма %s', (raw, key, orgForm) => {
    expect(counterpartyKey(raw)).toEqual({ key, orgForm });
  });

  it('один ключ у вариантов написания одного контрагента', () => {
    const variants = ['ООО «Ромашка»', 'РОМАШКА, ООО', 'ромашка ооо', 'Ромашка АО'];
    const keys = new Set(variants.map((v) => counterpartyKey(v).key));
    expect(keys).toEqual(new Set(['РОМАШКА']));
  });
});

describe('organizationNameKey (У-84)', () => {
  it('обычное имя → ключ, имя из одной орг-формы и пустое → null', () => {
    expect(organizationNameKey('ООО «Ромашка»')).toBe('РОМАШКА');
    expect(organizationNameKey('ООО')).toBeNull();
    expect(organizationNameKey('')).toBeNull();
  });
});
