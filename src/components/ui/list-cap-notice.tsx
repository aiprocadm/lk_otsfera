import React from 'react';

/**
 * Подпись под усечённым списком: «Показаны первые N из M» (`С-6`, сопровождение).
 *
 * Серверные списки без пагинации режутся по `take` (100–200 строк). Без
 * подписи человек читает экран как полный: «отложенных записей всего сто» —
 * а их триста. Примитив ничего не рисует, пока скрывать нечего: вызывающему
 * не нужен свой `if`, достаточно передать длину показанного и полный счётчик.
 *
 * `hint` — что делать, чтобы увидеть остальное. По умолчанию — уточнить
 * фильтр; у очередей без фильтра (корректировки) подсказка своя.
 */
export function ListCapNotice({
  shown,
  total,
  hint = 'Чтобы увидеть остальные, уточните фильтр.',
}: {
  /** Сколько строк на экране (обычно `rows.length`). */
  shown: number;
  /** Сколько строк подходит под условие всего — `count` по тому же `where`. */
  total: number;
  hint?: string;
}) {
  if (total <= shown) return null;
  return (
    <p className="text-xs text-gray-500 text-center" role="status">
      {/* template literal намеренно: React 19 вставляет comment-node между соседними {}-выражениями */}
      {`Показаны первые ${shown} из ${total}. ${hint}`}
    </p>
  );
}
