import type { Prisma } from '@prisma/client';

/**
 * Граница компании для лидов (`Р-Э7-2`, этап 7 ТЗ 12.09.2026).
 *
 * У модели `Lead` нет колонки `companyId`, поэтому компания достаётся через
 * связи. До этапа 7 воронка руководителя брала лид, если ответственный из этой
 * компании **или ответственного нет вовсе** — и тогда неназначенный лид любой
 * компании попадал в выборку каждой. Пока это была одна воронка, цена ошибки
 * была невелика; метрики и отчёты этапа 7 встали бы на то же правило, и в
 * выгрузку компании поехали бы чужие лиды.
 *
 * Правило теперь одно на все места: лид принадлежит компании, если из этой
 * компании его **ответственный** либо его **организация**. Лид без обеих связей
 * не принадлежит никому и в цифры компании не входит — это честнее, чем
 * приписать его всем сразу.
 */
export function leadCompanyWhere(companyId: string): Prisma.LeadWhereInput {
  return {
    OR: [{ assignedManager: { companyId } }, { organization: { companyId } }],
  };
}
