/**
 * Вкладки личных настроек (`У-114`).
 *
 * **Зачем реестр.** Одни и те же карточки — привязка Telegram, каналы
 * уведомлений, внутренний номер, коды восстановления, активные сессии — были
 * разложены в пяти кабинетах по-разному: у менеджера одной длинной страницей,
 * у партнёра четырьмя вкладками, у заказчика вперемешку с реквизитами
 * организации, у администратора и руководителя — двумя разными разделами хаба.
 * Человек, сменивший кабинет, искал своё заново.
 *
 * Теперь состав, названия, пояснения и порядок вкладок — здесь, а кабинет
 * показывает подмножество: различаются только права и наличие «Команды».
 */
export type PersonalSettingsTabKey = 'profile' | 'team' | 'notifications' | 'security';

export type PersonalSettingsTab = {
  key: PersonalSettingsTabKey;
  /** Название вкладки — одно на все кабинеты (§0.2, правило зеркала). */
  label: string;
  /** Подзаголовок в одну строку простыми словами (§15, «что здесь делают»). */
  description: string;
};

/** Порядок здесь — общий порядок вкладок во всех кабинетах. */
export const PERSONAL_SETTINGS_TABS: readonly PersonalSettingsTab[] = [
  {
    key: 'profile',
    label: 'Профиль',
    description: 'Ваши данные и способы связи с вами.',
  },
  {
    // `У-60`: «Команда» партнёра переехала сюда из главного меню.
    key: 'team',
    label: 'Команда',
    description: 'Кто из ваших сотрудников работает в кабинете и с какими клиентами.',
  },
  {
    key: 'notifications',
    label: 'Уведомления',
    description: 'О каких событиях сообщать и куда: Telegram, MAX, WhatsApp, почта.',
  },
  {
    key: 'security',
    label: 'Безопасность',
    description: 'Вход по одноразовому коду и активные сессии.',
  },
];

/**
 * Вкладки кабинета — фильтр реестра. «Команда» есть только там, где ею
 * управляют (партнёр-администратор), поэтому включается явно.
 */
export function personalSettingsTabsFor(opts: { team?: boolean } = {}): PersonalSettingsTab[] {
  return PERSONAL_SETTINGS_TABS.filter((t) => t.key !== 'team' || opts.team === true);
}

/**
 * Одна строка «что здесь делают» (§15) — общая на все пять кабинетов: раздел
 * один и тот же, значит и объяснение одно (правило зеркала §0.2).
 */
export const PERSONAL_SETTINGS_SUBTITLE =
  'Настройки, которые касаются лично вас: профиль, уведомления и вход в систему.';
