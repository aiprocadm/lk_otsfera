/**
 * Группы меню сотрудников учебного центра и их порядок (`У-113`).
 *
 * **Зачем.** Порядок групп был у каждого кабинета свой: у администратора меню
 * начиналось с «Платформы», у менеджера — с «Работы», у руководителя —
 * с «Настроек». Человек, перешедший из одного кабинета в другой, искал раздел
 * заново, хотя разделы те же самые.
 *
 * Теперь порядок — данные, а не случайность расстановки пунктов в реестре:
 * сайдбар сортирует группы по этому списку. Состав внутри группы по-прежнему
 * фильтруется правами и флагами, но переставить группы кабинет не может.
 */
export const MENU_GROUP_ORDER = [
  'Работа',
  'Продажи',
  'Клиенты',
  'Документы',
  'Финансы',
  'Коммуникации',
  'Аналитика',
  'Справочники',
  // Пре-хабовые разделы платформы («Здоровье системы», «Интеграции», «Аудит»,
  // «Доступ к персональным данным»). Видны только при выключенном флаге
  // `settings_hub` — при включённом их место занимает хаб «Настройки», и
  // группа исчезает вместе с ними.
  'Платформа',
] as const;

export type MenuGroup = (typeof MENU_GROUP_ORDER)[number];

/** Позиция группы в общем порядке; пункты без группы идут первыми. */
export function menuGroupRank(title: string): number {
  if (!title) return -1;
  const index = (MENU_GROUP_ORDER as readonly string[]).indexOf(title);
  // Неизвестная группа не должна молча уехать в начало меню: ставим её в
  // конец, а страж `navigation.menu-groups.guardrail` уронит сборку.
  return index === -1 ? MENU_GROUP_ORDER.length : index;
}
