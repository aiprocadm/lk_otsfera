/**
 * Реестр шлюзов — старых адресов, которые уводят на новое место (`У-263`).
 *
 * **Зачем реестр.** Шлюз — это обещание: «сохранённая ссылка не отдаст 404».
 * Обещание не бесплатное: каждый шлюз это файл, строка в меню-логике и лишний
 * переход у пользователя. Без даты появления шлюз живёт вечно — никто не
 * помнит, когда он возник, и убирать его страшно. С датой возраст считается
 * сам, и страж [`navigation.legacy-gateways`](../../__tests__/navigation.legacy-gateways.guardrail.test.ts)
 * краснеет, когда шлюз перевалил за 90 дней.
 *
 * **Почему 90 дней.** Это срок, за который закладка либо используется — и
 * человек один раз увидит новый адрес и переложит закладку, — либо забыта.
 * Держать дольше значит платить за то, чем никто не пользуется.
 *
 * **Здесь только кабинетные шлюзы.** Шлюзы хаба «Настройки» живут в своём
 * реестре ([settings.ts](./settings.ts), поле `legacyHrefs`): они привязаны к
 * разделам хаба, и разносить их по двум местам было бы хуже, чем иметь два
 * реестра с разным смыслом. Страж проверяет оба.
 *
 * **Удаление шлюза — отдельная работа, а не «заодно».** Перед удалением нужно
 * убедиться, что старого пути нет в ссылках писем и уведомлений: `У-263`
 * требует запроса к базе, потому что ссылка в уже отправленном письме живёт
 * дольше закладки.
 */
export type LegacyGateway = {
  /** Старый адрес, на который ещё приходят. */
  from: string;
  /** Куда уводит. */
  to: string;
  /** Когда адрес стал шлюзом, `ГГГГ-ММ-ДД`. */
  introducedAt: string;
  /** Почему переехало — простыми словами, для того, кто будет удалять. */
  reason: string;
};

