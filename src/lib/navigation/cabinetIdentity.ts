import type { Role } from '@/lib/auth/jwt';

/**
 * Название кабинета — одно на всю систему (`У-115`, §0.2 «правило зеркала»).
 *
 * Подпись в шапке собиралась в каждом каркасе по-своему: у партнёра это была
 * роль («Партнёр · Иван»), у заказчика — вообще не кабинет, а название
 * организации с почтой («ООО Ромашка · ivan@…»). Человек, у которого есть
 * доступ и туда и туда, видел две разные шапки и не понимал, где он.
 *
 * Теперь строка одна: «<Кабинет> · <имя или организация>». Название кабинета
 * живёт здесь и больше нигде — разъехаться ему негде.
 */
export const CABINET_NAMES: Record<Role | 'leader', string> = {
  admin: 'Кабинет администратора',
  manager: 'Кабинет менеджера',
  leader: 'Кабинет руководителя',
  partner: 'Кабинет партнёра',
  organization: 'Кабинет заказчика',
  student: 'Кабинет слушателя',
};

/**
 * Подпись в шапке: «<Кабинет> · <кто или какая организация>».
 *
 * Вторая половина необязательна: пока имя не заполнено, человек всё равно
 * должен видеть, в каком он кабинете, — поэтому точка-разделитель появляется
 * только вместе со второй половиной, а не висит в пустоте.
 */
export function cabinetHeaderTitle(
  role: Role | 'leader',
  subject: string | null
): { cabinet: string; subject: string | null } {
  const trimmed = subject?.trim() ?? '';
  return { cabinet: CABINET_NAMES[role], subject: trimmed === '' ? null : trimmed };
}
