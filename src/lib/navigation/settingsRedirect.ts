import { permanentRedirect } from 'next/navigation';
import { legacyRedirectMap } from '@/lib/navigation/settings';

/**
 * Шлюз старого маршрута (ТЗ §5.1): ни одна сохранённая ссылка не должна отдать
 * 404 — старый адрес уводит в хаб «Настройки» по карте редиректов.
 *
 * **Редирект постоянный (308).** Пока шёл флаг раскатки `settings_hub`, он был
 * временным (307) намеренно: 308 браузер кэширует навсегда, и откат флага
 * оставил бы пользователя с мёртвой навигацией. Флаг снят этапом 9 (`У-262`) —
 * хаб принят, откатывать нечего, и раздел переехал насовсем. Перевод 307 → 308
 * при снятии флага обещан CLAUDE.md §2b.
 *
 * Прежние страницы на старых адресах удалены вместе с веткой «флаг выключен»:
 * оставлять код, по которому никто не пройдёт, значит держать его и в покрытии.
 */
export function redirectToSettingsHub(legacyHref: string): void {
  const target = legacyRedirectMap().get(legacyHref);
  /* v8 ignore next -- пути без цели нет: соответствие карте закреплено тестом реестра */
  if (target) permanentRedirect(target);
}
