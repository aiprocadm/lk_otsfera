import { startOfMoscowDay } from '@/lib/dates/calendar';

/**
 * Сроки-даты по московскому дню — одно правило для задач и удостоверений
 * (прогон сопровождения №36, спека
 * `docs/superpowers/specs/2026-09-23-moscow-time-in-server-code-design.md`,
 * решение `Р-М-3`).
 *
 * **Что было сломано.** Просрочку считали сравнением «срок < сейчас». Срок из
 * формы задачи — это `<input type="date">`, он хранится полуночью UTC, то есть
 * 03:00 по Москве. Задача со сроком «25.09» становилась просроченной 25.09 в
 * 03:00 — в сам день срока: фильтр «Просроченные» и красная строка в списке
 * задач, уведомление «Задача просрочена» исполнителю ночью, счётчик у
 * руководителя. У удостоверений
 * граница была уже московской, но «вчера» считалось делением с округлением
 * вверх и давало `-0`: реестр по фильтру «Истекло» показывал удостоверение, а
 * значок рядом писал «Истекает через 0 дн.».
 *
 * **Правило.** Срок просрочен, когда закончился его **московский** день:
 * `срок < начало сегодняшних суток по Москве` (момент 00:00 МСК из
 * `lib/dates/calendar.ts`). Оно верно для обоих видов срока в базе:
 *  - «только дата» (полночь UTC из формы) — 03:00 МСК того же дня, день тот же;
 *  - «дата со временем» из Битрикс24 — например, `22:30Z` это 01:30 МСК
 *    СЛЕДУЮЩЕГО дня, и просрочен он по этому, московскому дню.
 *
 * Сравнение с «полуночью UTC московского дня» (`startOfMoscowDay` из
 * `documents/proposalExpiry.ts`) здесь НЕ годится: для срока `22:30Z` оно
 * объявило бы задачу просроченной на сутки раньше.
 *
 * **Почему пара «функция + условие выборки».** Одно и то же правило живёт и в
 * SQL (фильтр доски, счётчики, ночные уведомления), и в коде (значок, число
 * дней). Если выразить его дважды своими словами, они разойдутся на границе
 * суток — ровно это и случилось с удостоверениями. Поэтому обе формы собраны
 * здесь и считаются от одной и той же границы.
 *
 * Москва не переходит на летнее время с 2014 года: сутки — ровно 24 часа, и
 * «начало суток через N дней» — это просто сдвиг на N×24 часа.
 */

const DAY_MS = 24 * 60 * 60 * 1000;

/** Момент 00:00 МСК дня «сегодня + `offsetDays`» (отрицательный сдвиг — в прошлое). */
function moscowDayStart(now: Date, offsetDays: number): Date {
  return new Date(startOfMoscowDay(now).getTime() + offsetDays * DAY_MS);
}

/**
 * Сколько московских календарных дней от сегодняшнего до дня срока:
 * `0` — срок сегодня, `1` — завтра, `-1` — вчера (просрочен на один день).
 *
 * Деление с округлением ВНИЗ от начала сегодняшних суток даёт ровно номер
 * московского дня. Прежние формулы брали `Math.ceil`, и срок «вчера» при
 * границе в 00:00 МСК получал `ceil(-0.875) = -0`, а `-0 < 0` — это `false`.
 */
export function moscowDaysUntil(due: Date, now: Date): number {
  return Math.floor((due.getTime() - startOfMoscowDay(now).getTime()) / DAY_MS);
}

/**
 * Срок прошёл: его московский день закончился. Сравнение прямое, без счёта
 * дней — та же граница, что у {@link pastDueWhere}.
 */
export function isPastDue(due: Date, now: Date): boolean {
  return due.getTime() < startOfMoscowDay(now).getTime();
}

/**
 * Условие выборки «срок прошёл как минимум `minDays` московских дней назад».
 *
 * `minDays = 1` (по умолчанию) — просто «просрочен»: день срока закончился.
 * `minDays = 3` — идёт третий день просрочки (эскалация руководителю
 * `Company.taskOverdueEscalationDays`). Первый день просрочки — следующий
 * после дня срока, поэтому граница сдвигается на `minDays − 1` суток.
 */
export function pastDueWhere(now: Date, minDays = 1): { lt: Date } {
  return { lt: moscowDayStart(now, 1 - minDays) };
}

/**
 * Условие выборки «срок не позже конца дня „сегодня + `days`“ по Москве» —
 * вместе с уже просроченными. `days = 1` — «до конца завтрашнего дня».
 */
export function dueByWhere(now: Date, days: number): { lt: Date } {
  return { lt: moscowDayStart(now, days + 1) };
}

/**
 * Условие выборки «срок ещё не прошёл и наступит не позже, чем через `days`
 * московских дней»: от сегодняшнего дня (включительно) до дня
 * «сегодня + `days`» (включительно). Нижняя граница совпадает с
 * {@link pastDueWhere}: что не просрочено, то попадает сюда, без зазора и
 * без двойного счёта.
 */
export function dueWithinDaysWhere(now: Date, days: number): { gte: Date; lt: Date } {
  return { gte: startOfMoscowDay(now), ...dueByWhere(now, days) };
}
