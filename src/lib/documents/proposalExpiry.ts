import type { Prisma } from '@prisma/client';

/**
 * `У-164` (этап 7) — истечение срока коммерческого предложения.
 *
 * **Одно правило, два выражения.** Требование просит и «проверку при чтении»,
 * и ежедневную задачу. Разъехаться им нельзя: экран сказал бы «ещё
 * действует», а задача в ту же секунду перевела бы бумагу в «истёк срок» —
 * или наоборот. Поэтому здесь ровно одна граница и ровно четыре условия,
 * записанные дважды: чистой функцией для готовой строки и парным
 * `where`-строителем для выборки. Приём уже применён к удостоверениям
 * (`certificateStatus` + `statusWhere`) и к скрытому черновику
 * (`isHiddenFromClient` + `CLIENT_HIDDEN_DRAFT_WHERE`).
 *
 * **Почему `status === 'sent'` — часть правила, а не деталь выборки.** Срок
 * стоит уже у ЧЕРНОВИКА: он проставляется при выпуске. Без этого условия на
 * карточке черновика с прошедшей датой было бы написано «Истёк срок» — неправда,
 * клиенту его не отправляли; а задача каждую ночь ломилась бы в переход
 * `draft → expired`, которого нет в матрице, и засоряла бы журнал отказами.
 *
 * **Почему граница — начало суток по Москве.** В бумаге напечатано «Срок
 * действия: до 16.09.2026». Клиент, открывший письмо утром 16-го, не должен
 * получить «истекло»: это выглядит обманом, а не правилом. Поэтому
 * предложение действует ВЕСЬ последний день и становится истёкшим в 00:00
 * МСК следующего. Ошибиться в сторону «ещё действует» стоит одного лишнего
 * дня; ошибиться в другую — потерянной сделки.
 *
 * Пояс задан явно, а не берётся у процесса: сервер работает в UTC, а срок
 * человек читает по своему календарю. Тот же дефект уже ловили у года
 * документа (`Д-22`).
 */

/** Формат `YYYY-MM-DD` по московскому календарю. `en-CA` даёт ровно его. */
const MOSCOW_DAY = new Intl.DateTimeFormat('en-CA', { timeZone: 'Europe/Moscow' });

/**
 * Начало сегодняшних московских суток — в том же виде, в каком срок лежит в
 * базе (полночь UTC). Сравнивать надо с ним, а не с «сейчас»: иначе
 * предложение «истекало» бы в полдень последнего дня.
 */
export function startOfMoscowDay(now: Date): Date {
  return new Date(`${MOSCOW_DAY.format(now)}T00:00:00.000Z`);
}

/** Что нужно знать о документе, чтобы решить, истёк ли он. */
export type ProposalExpiryInput = {
  type: string;
  status: string;
  validUntil: Date | null;
};

/**
 * Истекло ли предложение. Сравнение ПРЯМОЕ, без счёта дней: формула
 * «разница в сутках < 0» даёт `-0` для вчерашнего срока с ненулевым временем,
 * а `-0 < 0` — это `false`. Чистая функция сказала бы «действует», а SQL с
 * тем же смыслом — «истекло»: ровно то расхождение, ради которого пару и
 * заводят.
 */
export function isProposalExpired(doc: ProposalExpiryInput, now: Date): boolean {
  return (
    doc.type === 'commercial_proposal' &&
    doc.status === 'sent' &&
    doc.validUntil !== null &&
    doc.validUntil.getTime() < startOfMoscowDay(now).getTime()
  );
}

/**
 * Тот же расчёт условием выборки. Четыре условия, тот же порядок, та же
 * граница — иначе задача и экран разойдутся.
 */
export function expiredProposalsWhere(now: Date): Prisma.DocumentWhereInput {
  return {
    type: 'commercial_proposal',
    status: 'sent',
    validUntil: { not: null, lt: startOfMoscowDay(now) },
  };
}

/**
 * Состояние документа ДЛЯ ПОКАЗА: расчёт на лету опережает хранимый статус.
 *
 * Задача переводит бумагу ночью, а человек может открыть карточку раньше.
 * Показывать «Отправлен» у предложения, срок которого вышел вчера, — значит
 * предложить нажать «Принять» и получить отказ. Считаем на сервере: клиентский
 * компонент, дёрнувший `new Date()` сам, дал бы разные значения при отрисовке
 * на сервере и в браузере — и мигающий статус.
 */
export function proposalDisplayStatus(doc: ProposalExpiryInput, now: Date): string {
  return isProposalExpired(doc, now) ? 'expired' : doc.status;
}
