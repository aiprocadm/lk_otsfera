/**
 * Что не вошло в архив (`У-252`) — чистый тип и чистая фраза по-русски.
 *
 * Отдельный файл БЕЗ единого серверного импорта. Сборка архива
 * (`services/documents/zip.ts`) тянет за собой хранилище, очередь и Prisma;
 * потяни кнопка эту функцию оттуда — серверный код уехал бы в браузерную
 * сборку, и `next build` упал бы, хотя все юнит-тесты остались бы зелёными.
 * Такое в проекте уже случалось (программа «Мессенджеры»).
 *
 * Фраза считается в ОДНОМ месте: сервер кладёт её в тело отказа, кнопка — в
 * подпись успешного скачивания. Две копии разошлись бы словами, и человек
 * читал бы про одно и то же по-разному.
 */

/**
 * Три разных причины — три разных ответа человеку: «не включено» (чужой или
 * удалённый), «ожидает проверки» (антивирус ещё не закончил), «в карантине»
 * (файл заражён). Четвёртая — файла нет в хранилище.
 */
export type ZipSkipped = {
  noAccess: number;
  pending: number;
  infected: number;
  /** Файла нет в хранилище — архив собираем без него, а не роняем целиком. */
  unavailable: number;
};

/**
 * Одна строка о том, что не вошло. Пусто, когда вошло всё: молчание здесь
 * честнее, чем «не включено: 0».
 */
export function zipSkippedSummaryRu(skipped: ZipSkipped): string {
  const parts: string[] = [];
  if (skipped.noAccess > 0) parts.push(`не включено: ${skipped.noAccess}`);
  if (skipped.pending > 0) parts.push(`ожидает проверки: ${skipped.pending}`);
  if (skipped.infected > 0) parts.push(`в карантине: ${skipped.infected}`);
  if (skipped.unavailable > 0) parts.push(`файл недоступен: ${skipped.unavailable}`);
  return parts.join(', ');
}
