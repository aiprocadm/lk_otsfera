/**
 * Реестр публичных API-адресов (`У-211`, `У-217`, решение `Р-3-8` спеки).
 *
 * Требование просило «добавить публичный адрес в allow-list middleware». В
 * этом проекте такого списка для API нет и быть не может: matcher middleware
 * исключает `/api/*` целиком, то есть API-адресов он не видит вовсе. Каждый
 * публичный адрес защищает себя сам — секретом, токеном, ограничением частоты.
 *
 * Поэтому «объявить публичность явно» здесь значит: перечислить такие адреса
 * в одном месте, с причиной на каждый. Смысл требования выполняется —
 * пополнить список публичных дверей молча нельзя: страж
 * `security.public-api-routes` сверяет реестр с кодом в обе стороны.
 *
 * Правило: адрес попадает сюда ТОЛЬКО если у него нет проверки сессии, и
 * рядом обязана стоять своя защита. Причина пишется по-русски и для человека:
 * её читают, когда через год спрашивают «а почему это открыто наружу».
 */

