import { parseIsoCalendarDate } from './calendar';

/**
 * «Настенное» московское время — дата со временем, записанная БЕЗ часового
 * пояса (прогон сопровождения №36, спека
 * `2026-09-23-moscow-time-in-server-code-design` §3 п. 5, решение `Р-М-4`).
 *
 * Поле `<input type="datetime-local">` отдаёт «2026-09-25T10:00» — без пояса.
 * `new Date(...)` читает такую строку в поясе ПРОЦЕССА, а сервер живёт по
 * Гринвичу: встреча «10:00» сохранялась как 10:00 UTC — то есть 13:00 по
 * Москве, и напоминание приходило на три часа позже. Браузер же ту же строку
 * читал по поясу компьютера: два конца одной формы понимали её по-разному.
 * Выгрузка Битрикс24 («03.11.2025 09:00:00») тоже приходит без пояса, а портал
 * заказчика живёт по Москве.
 *
 * Правило одно: время без пояса — московское. Смещение записано явным
 * `+03:00`: Москва не переходит на летнее время с 2014 года (тот же приём, что
 * в `lib/dates/calendar.ts` и `lib/calendar/month.ts`). Процесс при этом
 * остаётся в UTC (`Р-М-1`) — пояс задаётся здесь, а не переменной `TZ`.
 */

/**
 * `ГГГГ-ММ-ДДTчч:мм`, по желанию `:сс` и доли секунды. Часы 00–23, минуты и
 * секунды 00–59: «25:00» `Date` молча превратил бы в час ночи следующего дня.
 */
const WALL_CLOCK = /^\d{4}-\d{2}-\d{2}T([01]\d|2[0-3]):[0-5]\d(:[0-5]\d(\.\d+)?)?$/;

const MOSCOW_OFFSET = '+03:00';
const MOSCOW_OFFSET_MS = 3 * 60 * 60 * 1000;

/**
 * «2026-09-25T10:00» → момент 10:00 по Москве (`07:00Z`) или `null`, если
 * строка не такого вида или такого дня нет в календаре.
 *
 * `null`, а не «ближайшая похожая дата»: «30 февраля» `Date` молча переносит
 * на 2 марта, и человек получил бы встречу не в тот день, не увидев ошибки.
 * День сверяется тем же помощником, что и поля дат (`parseIsoCalendarDate`).
 */
export function parseMoscowWallClock(value: string): Date | null {
  if (!WALL_CLOCK.test(value)) return null;
  if (!parseIsoCalendarDate(value.slice(0, 10))) return null;
  return new Date(`${value}${MOSCOW_OFFSET}`);
}

/**
 * Момент → «ГГГГ-ММ-ДДTчч:мм» по Москве: значение для поля
 * `datetime-local` и основа подписей времени в календаре.
 *
 * Обратная к `parseMoscowWallClock`: что форма показала, то она и сохранит.
 * Прежде поле заполнялось по поясу браузера, а читалось по поясу сервера —
 * событие, открытое и сохранённое без правок, уезжало на три часа.
 * Арифметика вместо `Intl`: у Москвы смещение постоянное, а `Intl` в части
 * сборок ICU печатает полночь как «24:00». Дата обязана быть настоящей — сюда
 * приходят моменты из базы, а не ввод человека.
 */
export function toMoscowWallClockInput(date: Date): string {
  return new Date(date.getTime() + MOSCOW_OFFSET_MS).toISOString().slice(0, 16);
}
