/**
 * Нормализация ИНН перед поиском (ТЗ починки импорта, Т-20).
 *
 * Этап 4 — минимум: убрать все пробельные символы (включая неразрывные —
 * 1С любит вставлять их в числа). Этап 5 (Т-22) РАСШИРИТ эту же функцию:
 * приведение числа из Excel к строке и ведущие нули до 10 знаков — Т-20 требует
 * нормализовать ИНН партнёра «тем же кодом, что и ИНН организации», поэтому
 * точка правды одна, и растёт она в одном месте.
 */
export function normalizeInn(raw: string): string {
  return raw.replace(/\s+/g, '');
}
