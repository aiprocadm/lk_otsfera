/**
 * ИНН: нормализация, валидация, синтетический ключ (ТЗ починки импорта,
 * Т-16/Т-20/Т-21/Т-22). Единственная точка правды — этой же функцией
 * нормализуется ИНН партнёра (Т-20), и её же будет использовать откат (этап 9).
 */

/**
 * Нормализация ИНН (Т-22): убрать пробелы (включая неразрывные — 1С любит
 * вставлять их в числа) и восстановить ведущие нули. `0012345678` в Excel
 * часто приходит числом `12345678` — это частая скрытая причина «организация
 * не найдена» при существующей записи. Юрлица — 10 знаков, физлица/ИП — 12.
 * Не-цифровые строки (например slug сетевого обмена) не искажаются.
 */
export function normalizeInn(raw: string): string {
  const s = raw.replace(/\s+/g, '');
  if (!/^\d+$/.test(s)) return s;
  if (s.length < 10) return s.padStart(10, '0');
  if (s.length === 11) return s.padStart(12, '0');
  return s;
}

function checkDigit(digits: number[], weights: number[]): number {
  // Индекс доказуемо валиден: вызывающие проверяют длину строки регулярным
  // выражением, и digits всегда длиннее weights.
  const sum = weights.reduce((acc, w, i) => acc + w * digits[i]!, 0);
  return (sum % 11) % 10;
}

/**
 * Валидация ИНН (Т-21): 10 или 12 цифр и контрольная сумма по официальному
 * алгоритму ФНС. Мусор, неверная длина, битая контрольная цифра → false.
 */
export function isValidInn(inn: string): boolean {
  if (/^\d{10}$/.test(inn)) {
    const d = [...inn].map(Number);
    return checkDigit(d, [2, 4, 10, 3, 5, 9, 4, 6, 8]) === d[9];
  }
  if (/^\d{12}$/.test(inn)) {
    const d = [...inn].map(Number);
    return (
      checkDigit(d, [7, 2, 4, 10, 3, 5, 9, 4, 6, 8]) === d[10] &&
      checkDigit(d, [3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8]) === d[11]
    );
  }
  return false;
}

/**
 * Синтетический ключ контрагента из файла (Т-16, решение владельца №3):
 * `1c-inn:<нормализованный ИНН>`. Префикс обязателен — он отличает
 * синтетический ключ от настоящего `externalId`, пришедшего по сети из
 * `adapter-rest`. Один ИНН → один ключ, детерминированно.
 */
export function synthOrgExternalId(inn: string): string {
  return `1c-inn:${normalizeInn(inn)}`;
}
