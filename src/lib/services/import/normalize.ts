/**
 * Нормализация ярлыка из шапки 1С перед сравнением (ТЗ починки импорта, Т-8).
 *
 * Реальные выгрузки ломают точное сравнение пятью способами (П-7 ТЗ):
 * неразрывный пробел в шапке, «ё»/«е» («ИНН партнёра» / «ИНН партнера»),
 * регистр, двойные пробелы и перенос строки внутри ячейки. Все пять гасятся
 * здесь, в ОДНОЙ функции: ей пользуются и сопоставление листов, и сопоставление
 * колонок, и диагностика «что не распозналось» — иначе диагностика показывала
 * бы не то, на что смотрит рабочий код.
 *
 * `\s` в JavaScript покрывает и неразрывный пробел (U+00A0), и переносы строк.
 */
export function normalizeLabel(raw: string): string {
  return raw.replace(/\s+/g, ' ').trim().toLowerCase().replaceAll('ё', 'е');
}
