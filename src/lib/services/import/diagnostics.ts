/**
 * Диагностика разбора файла 1С (ТЗ починки импорта, Т-3).
 *
 * Ответ на вопрос пользователя «почему ничего не загрузилось»: что за листы
 * система увидела в книге, какие ожидала и какие заголовки не узнала. Это
 * НЕ ошибка сама по себе — блок показывается и при успешном разборе.
 *
 * Модуль намеренно без зависимостей: его тип импортирует и клиентская форма
 * импорта, поэтому тянуть сюда exceljs или серверный код нельзя.
 */

export type ImportDiagnostics = {
  /** Имена листов, фактически найденные в книге. */
  sheetsFound: string[];
  /** Имена листов, которые ищет текущая карта (`SHEET_NAMES`). */
  sheetsExpected: string[];
  /**
   * Фактическое имя листа → заголовки его первой строки, которых нет в карте
   * колонок. Ненайденного листа среди ключей нет вовсе — его отсутствие видно
   * по паре `sheetsFound`/`sheetsExpected`.
   */
  unmatchedHeaders: Record<string, string[]>;
};

/**
 * Заголовки шапки, не встречающиеся в карте колонок листа.
 *
 * Сравнение точное — ровно как в самом парсере (`colIndex.get(label)`), иначе
 * диагностика показывала бы не то, на что смотрит рабочий код. Нормализация
 * («ё/е», неразрывный пробел, регистр) придёт отдельным требованием Т-8.
 * Пустые ячейки шапки и повторы отбрасываются, порядок сохраняется — оператор
 * сверяет список со своей шапкой слева направо.
 */
export function unmatchedHeadersOf(headers: string[], cols: Record<string, string>): string[] {
  const known = new Set(Object.values(cols));
  const seen = new Set<string>();
  const unmatched: string[] = [];
  for (const raw of headers) {
    const header = raw.trim();
    if (!header || known.has(header) || seen.has(header)) continue;
    seen.add(header);
    unmatched.push(header);
  }
  return unmatched;
}
