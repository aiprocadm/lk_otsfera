import { normalizeLabel } from './normalize';

/**
 * Диагностика разбора файла 1С (ТЗ починки импорта, Т-3 + Т-11/Т-12).
 *
 * Ответ на вопрос пользователя «почему ничего не загрузилось»: что за листы
 * система увидела в книге, какие ожидала, какие заголовки не узнала и каких
 * обязательных колонок не хватает. Это НЕ ошибка сама по себе — блок
 * показывается и при успешном разборе.
 *
 * Модуль намеренно лёгкий: его тип импортирует и клиентская форма импорта,
 * поэтому тянуть сюда exceljs или серверный код нельзя.
 */

export type ImportDiagnostics = {
  /** Имена листов, фактически найденные в книге. */
  sheetsFound: string[];
  /** Основные имена листов, которые ищет текущая карта (`SHEET_NAMES[...][0]`). */
  sheetsExpected: string[];
  /**
   * Фактическое имя листа → заголовки его первой строки, которых нет в карте
   * колонок. Ненайденного листа среди ключей нет вовсе — его отсутствие видно
   * по паре `sheetsFound`/`sheetsExpected`.
   */
  unmatchedHeaders: Record<string, string[]>;
  /**
   * Фактическое имя листа → основные ярлыки ОБЯЗАТЕЛЬНЫХ колонок, которых в
   * нём не нашлось (Т-12). Лист без недостач в карте не значится.
   */
  missingColumns: Record<string, string[]>;
  /**
   * Основное имя вида листа → прочие листы книги, тоже подошедшие под его
   * алиасы. Берётся первый в порядке книги, но молча «съесть» второй нельзя —
   * оператор должен видеть неоднозначность.
   */
  duplicateSheets: Record<string, string[]>;
  /** Замечание о расхождении расширения файла и его содержимого (Т-14). */
  formatNote?: string | undefined;
};

/**
 * Заголовки шапки, не встречающиеся в карте колонок листа.
 *
 * С этапа 3 сравнение нормализованное (Т-8) — ровно то же, что использует сам
 * парсер, иначе диагностика показывала бы не то, на что смотрит рабочий код.
 * Возвращаются ИСХОДНЫЕ заголовки (как в файле): оператор сверяет список со
 * своей шапкой слева направо. Пустые ячейки и повторы отбрасываются.
 */
export function unmatchedHeadersOf(
  headers: string[],
  cols: Record<string, readonly string[]>
): string[] {
  const known = new Set(Object.values(cols).flat().map(normalizeLabel));
  const seen = new Set<string>();
  const unmatched: string[] = [];
  for (const raw of headers) {
    const header = raw.trim();
    const key = normalizeLabel(raw);
    if (!header || known.has(key) || seen.has(key)) continue;
    seen.add(key);
    unmatched.push(header);
  }
  return unmatched;
}
