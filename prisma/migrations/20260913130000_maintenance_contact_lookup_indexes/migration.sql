-- Сопровождение, хотфикс №50 (проверка `С-8`, прогон №27): карточка контакта
-- (этап 1 ТЗ 12.09.2026) на вкладках «Заказы» и «Сделки» ищет строки по
-- контакту — `Order.primaryContactId` и `Deal.contactId`. Индексов на этих
-- колонках не было: каждый открытый контакт перебирал таблицы заказов и сделок
-- целиком.
--
-- Миграция только добавляет индексы: ни одной строки не меняет.
CREATE INDEX "Order_primaryContactId_idx" ON "Order"("primaryContactId");
CREATE INDEX "Deal_contactId_idx" ON "Deal"("contactId");
