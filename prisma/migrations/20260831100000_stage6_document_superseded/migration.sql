-- Этап 6 (`У-151`): отметка «эта версия заменена перевыпуском».
-- Чисто аддитивно: у всех существующих строк NULL, то есть ни один документ
-- из списков не пропадает. Разбор исторических цепочек версий — отдельная
-- миграция данных (PR-8b), и она идёт ПОСЛЕ того, как код перестанет
-- зависеть от старой схемы номеров.
ALTER TABLE "Document" ADD COLUMN "supersededAt" TIMESTAMP(3);

-- Индекс под фильтр списков «показывать только действующую версию».
CREATE INDEX "Document_supersededAt_idx" ON "Document"("supersededAt");
