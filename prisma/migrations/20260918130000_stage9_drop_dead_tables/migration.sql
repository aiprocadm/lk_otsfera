-- Этап 9 (`У-261`): удаление мёртвых таблиц и чистка значений вне контракта.
-- Закрывает дефекты `Д-43` (модели `SavedView`, `Upload`) и `Д-47`
-- (`roleInPartner = 'member'`).
--
-- ПОРЯДОК РАБОТ (нарушать нельзя):
--   1. npm run report:dead-tables  — dry-run, только читает;
--   2. эта миграция.
--
-- Миграция САМА задаёт себе тот же вопрос, что и отчёт, и падает внятным
-- русским текстом. Молчаливого `DROP TABLE` здесь быть не должно: таблицу
-- удаляют один раз, а данные из неё после этого не вернуть. Отчёт отвечает на
-- вопрос ДО выкладки, миграция — в момент неё, на той базе, где всё и
-- происходит.

-- ---------------------------------------------------------------------------
-- Шаг 1. Убедиться, что удалять нечего.
-- ---------------------------------------------------------------------------
-- `SavedView` — сохранённые представления списков. Задел, который так и не
-- подключили: ни одного обращения в боевом коде за всё время жизни модели.
--
-- `Upload` — прежняя таблица файлов заказа. Писателя у неё нет: файлы живут в
-- `Document` и в объектном хранилище. Единственное чтение (запрет объединять
-- заказ с загрузками) снято предыдущим PR — счётчик всегда возвращал ноль.
DO $$
DECLARE
  n_saved_view bigint;
  n_upload     bigint;
BEGIN
  SELECT count(*) INTO n_saved_view FROM "SavedView";
  IF n_saved_view > 0 THEN
    RAISE EXCEPTION
      'Таблица "SavedView" не пуста: % строк. Удалять нельзя — сначала решите, что с этими данными. Подробности: npm run report:dead-tables',
      n_saved_view;
  END IF;

  SELECT count(*) INTO n_upload FROM "Upload";
  IF n_upload > 0 THEN
    RAISE EXCEPTION
      'Таблица "Upload" не пуста: % строк. Удалять нельзя — эти файлы нигде больше не записаны. Подробности: npm run report:dead-tables',
      n_upload;
  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- Шаг 2. Роль в партнёрстве приводится к контракту (`Д-47`).
-- ---------------------------------------------------------------------------
-- Значение `'member'` не существует ни в одном контракте: сервис партнёрской
-- команды объявляет `'admin' | 'manager'`, форма принимает эти же два, а сборка
-- сессии трактует «не admin» как `manager`. То есть человек со строкой
-- `'member'` и так работал менеджером — правим данные под уже существующее
-- поведение, ничего никому не меняя.
--
-- Бэкфилл идёт ПЕРЕД удалением таблиц намеренно: если шаг 1 упал, до этого
-- места выполнение не дойдёт, и база останется ровно такой, какой была.
UPDATE "PartnerUser"
   SET "roleInPartner" = 'manager'
 WHERE "roleInPartner" = 'member';

-- ---------------------------------------------------------------------------
-- Шаг 3. Удаление.
-- ---------------------------------------------------------------------------
-- Внешние ключи (`Upload.orderId` → `Order`, `SavedView.userId` → `User`)
-- уезжают вместе с таблицами: ограничение живёт на дочерней стороне.
DROP TABLE "Upload";
DROP TABLE "SavedView";
