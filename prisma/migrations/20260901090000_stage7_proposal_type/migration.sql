-- Этап 7 (`У-161`): новое значение типа документа — коммерческое предложение.
--
-- ОТДЕЛЬНОЙ миграцией намеренно: Postgres не разрешает использовать значение
-- перечисления в той же транзакции, где оно добавлено («New enum values must be
-- committed before they can be used»), а следующая миграция ссылается на него
-- в проверке целостности. Склеить их в одну — значит получить отказ на
-- выкладке, а не при разработке.
--
-- КП — предпродажный документ и в 1С не выгружается (решение `Р-14`).
ALTER TYPE "DocumentType" ADD VALUE IF NOT EXISTS 'commercial_proposal';
