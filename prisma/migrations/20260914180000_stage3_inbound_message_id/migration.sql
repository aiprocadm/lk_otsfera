-- `Message-ID` письма нужен, чтобы ответ менеджера встал в ТУ ЖЕ ветку у
-- клиента (заголовок `In-Reply-To`). Существующее поле `externalId` для этого
-- не годится: там лежит `email:<uid>` — ключ идемпотентности приёма, он
-- уникален и меняется при пересоздании ящика.
--
-- У писем, принятых до этой миграции, поле останется пустым: ответ на них
-- уйдёт без сшивки (отдельным письмом), но уйдёт — это лучше, чем ничего.
--
-- Обратный SQL (миграция обратима):
--   ALTER TABLE "InboundMessage" DROP COLUMN "externalMessageId";

-- AlterTable
ALTER TABLE "InboundMessage" ADD COLUMN     "externalMessageId" TEXT;
