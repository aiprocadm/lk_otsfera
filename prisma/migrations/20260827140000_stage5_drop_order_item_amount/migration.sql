-- Этап 5 ТЗ (`У-139`, решение `Р-13`): удаление `OrderItem.amount`.
--
-- Поле — задел этапа 8 v1.0 («попозиционный счёт»), который так и не
-- заполнялся: деньги переехали в `OrderLine`. PR-4 этого же этапа снял
-- последнее чтение — генератор документов печатает строки заказа, — поэтому
-- удаление колонки ничего не ломает.
--
-- ЗАЩИТА: миграция отказывается удалять колонку, если в ней есть хоть одно
-- значение. Требование ТЗ дословно: «переносить нечего — проверяется
-- миграцией, которая падает, если хоть одно значение не `null`». Молча
-- уронить деньги нельзя даже в поле, которое все считают мёртвым.
--
-- Перед выкладкой: `npm run report:order-item-amounts` (dry-run отчёт).
DO $$
DECLARE
  filled bigint;
BEGIN
  SELECT count(*) INTO filled FROM "OrderItem" WHERE "amount" IS NOT NULL;
  IF filled > 0 THEN
    RAISE EXCEPTION
      'OrderItem.amount: найдено % непустых значений — удаление отменено. Запустите npm run report:order-item-amounts и решите, куда переносить суммы.',
      filled;
  END IF;
END $$;

-- AlterTable
ALTER TABLE "OrderItem" DROP COLUMN "amount";
