-- Комментарии всегда читаются в разрезе заказа (карточка заказа у менеджера и
-- у заказчика, лента активности сделки) с сортировкой по дате. Единственный
-- существовавший индекс начинается с `authorId` и такому запросу не помогает,
-- поэтому каждое открытие заказа читало таблицу комментариев целиком.
--
-- CONCURRENTLY не используем: Prisma выполняет миграцию в транзакции, а
-- CREATE INDEX CONCURRENTLY в транзакции запрещён. Таблица небольшая —
-- короткая блокировка на запись приемлема.
CREATE INDEX "Comment_orderId_createdAt_idx" ON "Comment"("orderId", "createdAt");
